module Assistant
  module Reasoning
    module Tools
      class SprintTool < Base
        define "sprint",
               "A sprint's facts: items, open, remaining hours against everyone's capacity, per person, points.",
               { sprint: { type: "string", description: "Name or id; empty = current sprint" } }

        def call(args)
          sprint = context.sprint(args["sprint"])
          Assistant::Facts::SprintFacts.new(sprint).to_h
        end
      end
    end
  end
end
