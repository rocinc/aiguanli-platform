    def call
      settle_membership
      placed = 0
      TALK.each { |id, notes| placed += place(id, notes) { |day, hm| stamp(id, day, hm) } }
      BACKLOG_TALK.each { |id, notes| placed += place(id, notes) { |day, hm| ctx.at(ctx.monday + day, hm) } }
      say("TalkHistory #{placed} comments")
    end

