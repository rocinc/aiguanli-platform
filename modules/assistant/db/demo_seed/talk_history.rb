    # The seven human members carry the join date of the base dump; S1-S5 comments must come from people already in the project.
    def settle_membership
      joined = ctx.at(-80, "08:30")
      people = %i[ada sam frank fiona bob ben mia].map { user(it) }
      Member.where(project:, principal: people).where("created_at > ?", joined).update_all(created_at: joined, updated_at: joined)
      Assistant::Event.where(kind: "member_added", subject: people, project:).where("created_at > ?", joined).update_all(created_at: joined)
    end

    def catalog_sprints
      @catalog_sprints ||= YAML.safe_load_file(CATALOG, aliases: true).fetch("history", []).to_h { [it["id"], it["sprint"]] }
    rescue Errno::ENOENT
      {}
    end

    def sprint_of(id) = EXISTING_SPRINT[id] || catalog_sprints[id]

    def stamp(id, day, hm)
      sprint = sprint_of(id)
      raise "no sprint known for ##{id}" unless sprint

      ctx.at(ctx.monday + SPRINT_START.fetch(sprint) + (7 * (day / 5)) + (day % 5), hm)
    end

    def place(id, notes)
      wp = WorkPackage.find_by(id:, project:)
      return skip(id, "work package not found") unless wp

      timed = before_closing(id, notes.map { |day, hm, who, text, flag| [yield(day, hm), who, text, flag] })
      born = Journal.where(journable_type: "WorkPackage", journable_id: id).minimum(:created_at)
      return skip(id, "comments before the work package exists") if timed.any? { |time,| time <= born }

      created = timed.sort_by(&:first).map { |time, who, text,| [comment(wp, who, text), time] }
      reorder(wp, created)
      created.size
    rescue RuntimeError => e
      skip(id, e.message)
    end

    # backbone closes each package at a fixed hour on its last day; remarks meant for the open phase
    # (everything not marked :after_close) are moved to just before that moment.
    def before_closing(id, timed)
      closing = Journal.where(journable_type: "WorkPackage", journable_id: id).order(:version)
                       .find { it.data.status_id == AssistantSeed::STATUSES[:closed] }&.created_at
      return timed unless closing

      late = timed.select { |time, _, _, flag| flag.nil? && time >= closing }.sort_by(&:first)
      moved = late.each_with_index.to_h { |entry, index| [entry, closing - ((late.size - index) * 9).minutes] }
      timed.map { |entry| moved.key?(entry) ? [moved[entry], *entry[1..]] : entry }
    end

    def skip(id, reason)
      say("TalkHistory skipped ##{id}: #{reason}")
      0
    end

    def comment(wp, who, text)
      as(who) do
        fresh = WorkPackage.find(wp.id)
        fresh.journal_notes = text
        fresh.updated_at = Time.current
        fresh.save!(validate: false)
        fresh.journals.reorder(:version).last.id
      end
    end

    # Interleaves the freshly written comment journals with the journals that already exist, by time:
    # versions, validity periods, events and the attribute snapshot of each comment follow its new position.
    def reorder(wp, created)
      times = created.to_h
      journals = Journal.where(journable_type: "WorkPackage", journable_id: wp.id).order(:version).to_a
      journals.each { |journal| journal.created_at = times[journal.id] if times.key?(journal.id) }
      ordered = journals.sort_by { [it.created_at, it.version] }
      ordered.each_cons(2) { |before, after| after.created_at = before.created_at + 1.second if after.created_at <= before.created_at }

      copy_snapshots(ordered, times)
      renumber(ordered)
      WorkPackage.where(id: wp.id).update_all(updated_at: ordered.last.created_at)
    end

    def copy_snapshots(ordered, times)
      ordered.each_cons(2) do |before, after|
        next unless times.key?(after.id)

        after.data.update_columns(before.data.attributes.except("id"))
        Journal::CustomizableJournal.where(journal_id: after.id).delete_all
        before.customizable_journals.each { Journal::CustomizableJournal.create!(it.attributes.except("id").merge("journal_id" => after.id)) }
        Journal::AttachableJournal.where(journal_id: after.id).delete_all
        before.attachable_journals.each { Journal::AttachableJournal.create!(it.attributes.except("id").merge("journal_id" => after.id)) }
      end
    end

    def renumber(ordered)
      parking = Time.zone.parse("3000-01-01")
      ordered.each_with_index do |journal, index|
        journal.update_columns(version: journal.version + 100_000,
                               validity_period: ((parking + index.days)...(parking + index.days + 1.hour)))
      end
      ordered.each_with_index do |journal, index|
        following = ordered[index + 1]&.created_at
        journal.update_columns(version: index + 1, created_at: journal.created_at, updated_at: journal.created_at,
                               validity_period: (journal.created_at...following))
        Assistant::Event.where(journal_id: journal.id).update_all(created_at: journal.created_at)
      end
    end
