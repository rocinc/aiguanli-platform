    include Support

    CHILD_TABLES = %w[customizable_journals attachable_journals work_package_version_journals].freeze
    DEADLINE = "non_overlapping_journals_validity_periods"

    def call
      placed = Hash.new { |hash, key| hash[key] = [] }
      threads.each do |id, lines|
        lines.sort_by { |day, hm, *| [slot_key(day), hm] }.each do |day, hm, who, text|
          time = stamp(day, hm)
          placed[id] << [post(id, who, text, time), time]
        end
      end
      placed.each { |id, entries| settle(id, entries) }
      say("talk now comments=#{placed.values.sum(&:size)}")
    end

    private

    def slot_key(day) = day == :today ? 99 : day

    def limit = ctx.now - 2.minutes

    def stamp(day, hm)
      time = ctx.at(day == :today ? ctx.today : day, hm)
      [time, limit].min
    end

    def post(id, who, text, time)
      as(who) do
        work_package = WorkPackage.find(id)
        work_package.journal_notes = text
        work_package.updated_at = time
        work_package.save!
      end
      Journal.where(journable_type: "WorkPackage", journable_id: id).order(:id).last.id
    end

    def ping(key)
      principal = key == :assistant ? AssistantUser.first : user(key)
      name = "#{principal.firstname} #{principal.lastname}"
      %(<mention class="mention" data-id="#{principal.id}" data-type="user" data-text="@#{name}">@#{name}</mention>)
    end

    # Journals are strictly ordered by time, so a comment dated before a later state change is written at the end and
    # then moved: it takes the work package state of the journal it now follows, and versions and validity are renumbered.
    def settle(id, entries)
      connection = ActiveRecord::Base.connection
      connection.transaction do
        connection.execute("SET CONSTRAINTS #{DEADLINE} DEFERRED")
        journals = Journal.where(journable_type: "WorkPackage", journable_id: id)
        fresh = entries.map(&:first)
        originals = journals.where.not(id: fresh).order(:version).to_a
        used = originals.map(&:created_at)
        entries.sort_by(&:last).each do |journal_id, time|
          time = [time, originals.first.created_at + 1.second].max
          time += 1.second while used.any? { (it - time).abs < 1 }
          used << time
          journal = Journal.find(journal_id)
          source = originals.reverse.find { it.created_at <= time } || originals.first
          clone_state(journal, source)
          journal.update_columns(created_at: time, updated_at: time)
          Assistant::Event.where(journal_id:).update_all(created_at: time)
        end
        renumber(journals)
        connection.execute("SET CONSTRAINTS #{DEADLINE} IMMEDIATE")
        WorkPackage.where(id:).update_all(updated_at: journals.maximum(:created_at))
      end
    end

    def clone_state(journal, source)
      data = Journal::WorkPackageJournal.find(source.data_id).dup
      data.save!
      stale = journal.data_id
      journal.update_columns(data_id: data.id)
      Journal::WorkPackageJournal.where(id: stale).delete_all
      connection = ActiveRecord::Base.connection
      CHILD_TABLES.each do |table|
        columns = (connection.columns(table).map(&:name) - %w[id journal_id]).join(", ")
        connection.execute("DELETE FROM #{table} WHERE journal_id = #{journal.id}")
        connection.execute("INSERT INTO #{table} (journal_id, #{columns}) SELECT #{journal.id}, #{columns} FROM #{table} WHERE journal_id = #{source.id}")
      end
    end

    def renumber(journals)
      ordered = journals.order(:created_at, :id).to_a
      journals.update_all("version = version + 100000")
      ordered.each_with_index do |journal, index|
        following = ordered[index + 1]&.created_at
        journal.update_columns(version: index + 1, validity_period: (journal.created_at...following))
      end
    end

